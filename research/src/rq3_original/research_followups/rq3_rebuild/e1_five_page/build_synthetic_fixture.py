#!/usr/bin/env python3
"""Invented acceptance data only. Expected arithmetic is recorded independently."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def build():
    tables = {k: [] for k in ("moodle", "echo", "gdocs", "features", "reply_network", "view_network", "goals", "reflections")}
    # learner, course, observation week, resource events, clicks, posts, replies, views
    groups = [("SYN_A", "COURSE_A", 1, 3, 2, 2, 1, 4),
              ("SYN_A", "COURSE_A", 2, 7, 4, 5, 3, 6),
              ("SYN_B", "COURSE_A", 1, 11, 2, 8, 6, 9),
              ("SYN_A", "COURSE_B", 1, 17, 7, 9, 5, 8)]
    for sid, course, week, *counts in groups:
        for event, count in zip(("Resources_views", "Video_views", "Debate_posts", "Debate_replies", "Debate_views"), counts):
            for _ in range(count):
                tables["moodle"].append({"ID": sid, "Course": course, "Time": "2026-09-" + ("01" if week == 1 else "08") + "T10:00:00+02:00",
                    "Week": week, "Content_week": 1, "Day_of_week": "Tuesday", "Event": event,
                    "Activity": "Debate" if event.startswith("Debate") else "Lecture" if event == "Video_views" else "Resources",
                    "Item_ID": "V1", "Event_ID": "SYN_EVENT_" + str(len(tables["moodle"]))})
    for sid, course, week, rows in [
        ("SYN_A", "COURSE_A", 1, [("V1", 2, 40), ("V2", 4, 80)]),
        ("SYN_A", "COURSE_A", 2, [("V1", 10, 100)]),
        ("SYN_B", "COURSE_A", 1, [("V1", 2, 40), ("V2", 4, 80)]),
        ("SYN_A", "COURSE_B", 1, [("V1", 20, 20)])]:
        for item, views, percent in rows:
            tables["echo"].append({"ID": sid, "Course": course, "Observation_week": week, "Content_week": 1,
                "Class": "Synthetic " + item, "Item_ID": item, "Video Views": views, "Video View %": percent,
                "Event_ID": "SYN_ECHO_" + str(len(tables["echo"]))})
    for sid, course, week, values in [("SYN_A", "COURSE_A", 1, [100, 50]), ("SYN_A", "COURSE_A", 2, [900]),
                                    ("SYN_B", "COURSE_A", 1, [700]), ("SYN_A", "COURSE_B", 1, [600])]:
        for value in values:
            tables["gdocs"].append({"ID": sid, "Course": course, "Week": week, "absStrCount": value,
                                  "dayOfWeek": "Tuesday", "Event_ID": "SYN_GDOC_" + str(len(tables["gdocs"]))})
        for table in ("goals", "reflections"):
            tables[table].append({"ID": sid, "Course": course, "Week": week, "text": "SYNTHETIC_PRIVATE_TEXT_" + sid + "_" + course + "_W" + str(week)})
        tables["features"].append({"ID": sid, "Course": course, "Resources_views": 999,
                                   "Debate_posts": 999, "Video_views_sum": 999, "Total_chars": 999})
    for table in ("reply_network", "view_network"):
        for course, week, from_id, to_id, n in [
            ("COURSE_A", 1, "SYN_A", "SYN_B", 2), ("COURSE_A", 1, "SYN_B", "SYN_A", 3),
            ("COURSE_A", 1, "SYN_A", "SYN_A", 10), ("COURSE_A", 2, "SYN_A", "SYN_B", 70),
            ("COURSE_B", 1, "SYN_A", "SYN_B", 90)]:
            tables[table].append({"From": from_id, "To": to_id, "Course": course, "week": week, "count": n,
                                  "Event_ID": "SYN_" + table + "_" + str(len(tables[table]))})
    fixture = {"origin": "SYNTHETIC", "description": "Invented people, courses, events, optional text and coverage only.",
               "tables": tables, "columns": {k: list(v[0]) for k, v in tables.items()}}
    expected = {"authority": "Hand arithmetic written before calling implementation; not generated by aggregator.",
                "A_COURSE_A_W1": {"resource_views": 3, "video_clicks": 2, "video_views": 6, "mean_view_percent": 60,
                                  "debate_posts": 2, "debate_replies": 1, "debate_views": 4, "edited_characters": 150},
                "A_COURSE_A_W2": {"resource_views": 7, "video_clicks": 4, "video_views": 10, "mean_view_percent": 100,
                                  "debate_posts": 5, "debate_replies": 3, "debate_views": 6, "edited_characters": 900},
                "B_COURSE_A_W1": {"resource_views": 11, "video_clicks": 2, "video_views": 6, "mean_view_percent": 60,
                                  "debate_posts": 8, "debate_replies": 6, "debate_views": 9, "edited_characters": 700},
                "A_COURSE_B_W1": {"resource_views": 17, "video_clicks": 7, "video_views": 20, "mean_view_percent": 20,
                                  "debate_posts": 9, "debate_replies": 5, "debate_views": 8, "edited_characters": 600},
                "A_NETWORK_COURSE_A_W1": {"sent": 2, "received": 3, "unique_sent": 1, "unique_received": 1},
                "A_V1_W1": {"video_views": 2, "mean_view_percent": 40}}
    for name, value in (("SYNTHETIC_FIXTURE.json", fixture), ("HAND_CALCULATED_EXPECTATIONS.json", expected)):
        (HERE / name).write_text(json.dumps(value, indent=2) + "\n")


if __name__ == "__main__":
    build()
