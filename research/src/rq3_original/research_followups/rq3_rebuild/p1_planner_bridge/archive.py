"""Allowlisted, committed-byte review packaging and standalone verification."""
from pathlib import Path,PurePosixPath
from hashlib import sha256
from datetime import datetime,timezone
import argparse,io,json,stat,subprocess,zipfile

ROOT=Path(__file__).resolve().parent
START='945c99563d3220ef4b8b7eb9eac06570d6173336'
BRANCH='research/rq3-rebuild-p1-planner-bridge'
PREFIX='research_followups/rq3_rebuild/p1_planner_bridge/'
ARCHIVE_ROOT='RQ3_REBUILD_P1_PLANNER_BRIDGE_REVIEW_2026-09-06'
MANIFEST='packaging/OUTPUT_MANIFEST.json'


def blob_entry(path,blob):return dict(path=path,bytes=len(blob),sha256=sha256(blob).hexdigest())

def json_bytes(obj):return (json.dumps(obj,ensure_ascii=False,indent=2)+'\n').encode()


def make_archive(payload):
    if MANIFEST in payload:raise ValueError('Manifest generated here only.')
    members=[blob_entry(p,b) for p,b in sorted(payload.items())]
    manifest=dict(version='P1_REVIEW_MANIFEST_V1',scope='Every archive member except this manifest; archive hash external.',
                  excluded_self=MANIFEST,members=members)
    content={**payload,MANIFEST:json_bytes(manifest)}
    stream=io.BytesIO()
    with zipfile.ZipFile(stream,'w',zipfile.ZIP_DEFLATED) as z:
        for path,blob in sorted(content.items()):
            info=zipfile.ZipInfo(ARCHIVE_ROOT+'/'+path,date_time=(2026,9,6,0,0,0))
            info.create_system=3;info.external_attr=(stat.S_IFREG|0o644)<<16
            info.compress_type=zipfile.ZIP_DEFLATED;z.writestr(info,blob)
    return stream.getvalue(),content


def verify(blob_or_path,expected=None):
    stream=io.BytesIO(blob_or_path) if isinstance(blob_or_path,bytes) else blob_or_path
    with zipfile.ZipFile(stream) as z:
        names=z.namelist()
        if len(names)!=len(set(names)):raise ValueError('Duplicate ZIP members.')
        for info in z.infolist():
            p=PurePosixPath(info.filename)
            mode=(info.external_attr>>16)&0xffff
            if (p.is_absolute() or '..' in p.parts or '\\' in info.filename or '\x00' in info.filename
                or not p.parts or p.parts[0]!=ARCHIVE_ROOT or len(p.parts)<2
                or info.filename!=str(p) or (mode and not stat.S_ISREG(mode)) or info.is_dir()):
                raise ValueError('Unsafe/nonregular ZIP path: '+info.filename)
        if z.testzip() is not None:raise ValueError('CRC failure.')
        key=ARCHIVE_ROOT+'/'+MANIFEST
        if key not in names:raise ValueError('Missing manifest.')
        m=json.loads(z.read(key));entries=m['members']
        paths=[e['path'] for e in entries]
        if len(paths)!=len(set(paths)) or MANIFEST in paths:raise ValueError('Invalid manifest member scope.')
        allowed={ARCHIVE_ROOT+'/'+p for p in paths}|{key}
        if set(names)!=allowed:raise ValueError('Extra or missing ZIP members.')
        for e in entries:
            b=z.read(ARCHIVE_ROOT+'/'+e['path'])
            if len(b)!=e['bytes'] or sha256(b).hexdigest()!=e['sha256']:raise ValueError('Member hash/size mismatch: '+e['path'])
        actual={str(PurePosixPath(n).relative_to(ARCHIVE_ROOT)):z.read(n) for n in names}
        if expected is not None and actual!=expected:raise ValueError('Archive differs from expected committed/generated bytes.')
        return dict(crc='PASS',path_safety='PASS',duplicates='NONE',missing_members=[],extra_members=[],
                    member_sizes_and_sha256='PASS',file_count=len(names),members=[blob_entry(p,b) for p,b in sorted(actual.items())])


def build(destination):
    repo=ROOT.parents[2]
    def git(*args):return subprocess.check_output(['git','-C',str(repo),*args])
    head=git('rev-parse','HEAD').decode().strip();branch=git('branch','--show-current').decode().strip()
    status=git('status','--porcelain=v1').decode()
    if branch!=BRANCH or git('rev-parse','HEAD^').decode().strip()!=START or git('rev-list','--count',START+'..HEAD').strip()!=b'1' or status:
        raise RuntimeError('Git ending gates failed; no branch repair permitted.')
    if git('show','-s','--format=%s','HEAD').decode().strip()!='RQ3-REBUILD-P1: bridge memory validity and prepare bounded planning requests':raise RuntimeError('Unexpected commit subject.')
    changes=git('diff','--name-status',START,head).decode().splitlines()
    if not changes or any(not x.startswith('A\t'+PREFIX) for x in changes):raise RuntimeError('Out-of-scope or modified inherited path.')
    paths=git('ls-tree','-r','--name-only',head,'--',PREFIX).decode().splitlines()
    payload={p[len(PREFIX):]:git('show',head+':'+p) for p in paths}
    # Explicit policy excludes DBs/weights/private identities; payload consists only
    # of committed P1 sources, reports, source-bound exposed synthetic dependencies.
    blocked={'.db','.sqlite','.sqlite3','.safetensors','.pt','.pkl','.zip','.env','.key'}
    if any(Path(p).suffix in blocked or Path(p).name in {'.DS_Store','credentials.json'} for p in payload):raise RuntimeError('Disallowed artifact type in payload.')
    receipt=dict(start_head=START,end_head=head,parent=START,branch=branch,cwd=str(repo),commit_count=1,
                 status_before_packaging=status,changed_paths=changes,utc=datetime.now(timezone.utc).isoformat(),
                 no_llm_or_judge_calls=True,only_owned_scope_changed=True)
    payload['packaging/GIT_START_END.json']=json_bytes(receipt)
    payload['packaging/FULL_TASK_DIFF.patch']=git('diff','--binary',START,head,'--',PREFIX)
    code_paths=[p for p in paths if p.endswith('.py') and '/inherited_' not in p]
    payload['packaging/P1_CODE_DIFF.patch']=git('diff','--binary',START,head,'--',*code_paths)
    payload['packaging/EXPORT_POLICY.json']=json_bytes(dict(mode='REVIEW_ONLY',source='Exact committed owned bytes plus post-commit Git receipts/diffs/manifests',
        exclusions=['Full repository','private student/course data','Human/Judge ratings','credentials','weights','original private databases','active E1/R1/M1 outputs'],
        synthetic_dependencies='Frozen P0 test assets and selected M0 saved envelopes are exposed development material; no independent Gold.'))
    blob,content=make_archive(payload);inside=verify(blob,content)
    payload['packaging/PREWRITE_VERIFICATION.json']=json_bytes({k:v for k,v in inside.items() if k!='members'}|{'scope':'Committed/generated payload before this receipt and final manifest; final archive verified again after writing.'})
    blob,content=make_archive(payload)
    dest=Path(destination)
    if dest.exists():raise FileExistsError('Refusing to overwrite existing review ZIP: '+str(dest))
    # Exclusive create; final verifier reads the actual file, not the in-memory ZIP.
    with dest.open('xb') as f:f.write(blob)
    result=verify(dest,content)
    result.update(path=str(dest.resolve()),sha256=sha256(dest.read_bytes()).hexdigest(),bytes=dest.stat().st_size,
        verified_at_utc=datetime.now(timezone.utc).isoformat(),git=receipt)
    (ROOT/'packaging').mkdir(exist_ok=True)
    (ROOT/'packaging/GIT_START_END.json').write_bytes(json_bytes(receipt))
    (ROOT/'packaging/ZIP_READBACK_RECEIPT.json').write_bytes(json_bytes(result))
    print(json.dumps({k:v for k,v in result.items() if k not in ('members','git')},indent=2))
    return result


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('mode',choices=['build','verify']);parser.add_argument('path');args=parser.parse_args()
    if args.mode=='build':build(args.path)
    else:print(json.dumps(verify(args.path),indent=2))
